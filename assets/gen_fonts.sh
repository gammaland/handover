#!/bin/bash
# Generates src/fonts_src.py: the content hash of each font, used as ?v= for cache busting. Don't edit the output by hand.
# The font files themselves are static assets in public/ (scripts/build.sh, D61); the Worker doesn't serve them.
# Why self-host instead of Google Fonts: external fonts send every visitor's IP to a third party,
# which contradicts "IPs are erased after 30 days" (D28). Font license: SIL OFL 1.1, see assets/fonts/LICENSE.txt
set -e
cd "$(dirname "$0")/.."
python3 - <<'PY'
import glob, hashlib, os
fonts = {os.path.basename(p): hashlib.sha256(open(p, "rb").read()).hexdigest()[:10]
         for p in sorted(glob.glob("assets/fonts/*.woff2"))}
with open("src/fonts_src.py", "w") as f:
    f.write('"""Generated by assets/gen_fonts.sh from assets/fonts/*.woff2. Do not edit."""\n')
    f.write(f"FONTS = {fonts!r}   # file name -> content hash\n")
print("fonts_src.py:", ", ".join(f"{k} ({v})" for k, v in fonts.items()))
PY
